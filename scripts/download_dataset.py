#!/usr/bin/env python3
"""
download_dataset.py — Selective, resumable downloader for public DAS datasets.

SAFETY GUARANTEES:
1. Refuses to write waveform data into git-tracked directories inside the repo.
2. Automatically writes a local `.gitignore` (`*`) into the target download folder.
3. Runs in `--dry-run` mode by default unless `--execute` is explicitly provided.

Usage examples:
  # Preview files matching a date or pattern from a crawled manifest:
  python3 scripts/download_dataset.py --manifest manifests/uw-ooi-rca-2024.json --match "20240506.*\\.h5$"

  # Download the first 2 metadata/sample files to an external or git-ignored directory:
  python3 scripts/download_dataset.py --manifest manifests/uw-ooi-rca-2021.json \
      --match "metadata/.*" --limit 2 --dest ~/das_data/uw-ooi-rca-2021 --execute
"""

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import urllib.request
from pathlib import Path
from typing import Any, Dict, List

REPO_ROOT = Path(__file__).resolve().parent.parent
ALLOWED_IN_REPO_DIRS = {"downloads", "data", "raw", "cache", "scratch"}


def verify_safe_destination(dest: Path) -> Path:
    """Ensure the destination is never a git-tracked path inside the repository."""
    resolved = dest.expanduser().resolve()
    try:
        rel = resolved.relative_to(REPO_ROOT)
        top_part = rel.parts[0] if rel.parts else ""
        if top_part not in ALLOWED_IN_REPO_DIRS:
            sys.exit(
                f"SAFETY BLOCK: Refusing to download data into repo path '{resolved}'.\n"
                f"Use an external path (e.g. ~/das_data/...) or a git-ignored directory ({', '.join(sorted(ALLOWED_IN_REPO_DIRS))})."
            )
    except ValueError:
        # Outside REPO_ROOT is always safe from polluting this repo
        pass

    return resolved


def ensure_local_gitignore(dest: Path) -> None:
    """Create a guard .gitignore inside the download directory so git never tracks its contents."""
    dest.mkdir(parents=True, exist_ok=True)
    gi = dest / ".gitignore"
    if not gi.exists():
        gi.write_text("# Automatically generated by download_dataset.py — never commit data\n*\n", encoding="utf-8")


def download_http_file(url: str, target_path: Path, timeout: int = 60) -> Dict[str, Any]:
    """Download a single file with HTTP Range resume support and SHA-256 calculation."""
    target_path.parent.mkdir(parents=True, exist_ok=True)
    part_path = target_path.with_suffix(target_path.suffix + ".part")

    existing_bytes = part_path.stat().st_size if part_path.exists() else 0
    headers = {"User-Agent": "DAS-Selective-Downloader/1.0"}
    if existing_bytes > 0:
        headers["Range"] = f"bytes={existing_bytes}-"

    req = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        status = resp.status
        mode = "ab" if (status == 206 and existing_bytes > 0) else "wb"
        with part_path.open(mode) as out_f:
            while True:
                chunk = resp.read(1024 * 1024)  # 1 MiB chunks
                if not chunk:
                    break
                out_f.write(chunk)

    part_path.replace(target_path)

    sha256 = hashlib.sha256()
    with target_path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            sha256.update(block)

    return {
        "path": str(target_path),
        "bytes": target_path.stat().st_size,
        "sha256": sha256.hexdigest(),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Selective, repo-safe DAS dataset downloader.")
    parser.add_argument("--manifest", required=True, help="Path to crawled manifest JSON (manifests/<id>.json)")
    parser.add_argument("--match", help="Regex filter on relative_path or URL (e.g. '20240506/.*\\.h5$')")
    parser.add_argument("--limit", type=int, default=5, help="Max number of files to download in one run (default: 5)")
    parser.add_argument(
        "--dest",
        default=str(REPO_ROOT / "downloads"),
        help="Destination root directory (must be outside repo or inside git-ignored downloads/)",
    )
    parser.add_argument(
        "--execute",
        action="store_true",
        help="Actually perform the download (if omitted, runs in safe --dry-run preview mode)",
    )
    args = parser.parse_args()

    manifest_path = Path(args.manifest)
    if not manifest_path.exists():
        sys.exit(f"Manifest not found: {manifest_path}")

    with manifest_path.open("r", encoding="utf-8") as f:
        manifest = json.load(f)

    dataset_id = manifest.get("dataset_id", manifest_path.stem)
    dest_root = verify_safe_destination(Path(args.dest)) / dataset_id

    files: List[Dict[str, Any]] = manifest.get("files", [])
    if args.match:
        rx = re.compile(args.match)
        files = [
            item for item in files
            if rx.search(item.get("relative_path", "")) or rx.search(item.get("url", ""))
        ]

    total_matched = len(files)
    selected = files[: args.limit] if args.limit > 0 else files

    print(f"Dataset ID     : {dataset_id}")
    print(f"Matched Files  : {total_matched} (selecting {len(selected)} with --limit={args.limit})")
    print(f"Target Folder  : {dest_root}")
    print(f"Mode           : {'EXECUTE (downloading)' if args.execute else 'DRY-RUN (preview only — pass --execute to download)'}")
    print("-" * 80)

    for idx, item in enumerate(selected, start=1):
        rel = item["relative_path"]
        url = item["url"]
        size_hint = item.get("size_hint") or "unknown size"
        target_file = dest_root / rel

        if not args.execute:
            print(f"[{idx}/{len(selected)}] WOULD DOWNLOAD: {url} ({size_hint}) -> {target_file}")
            continue

        ensure_local_gitignore(dest_root)
        if target_file.exists():
            print(f"[{idx}/{len(selected)}] SKIP (already exists): {target_file}")
            continue

        print(f"[{idx}/{len(selected)}] DOWNLOADING: {url} ({size_hint}) -> {target_file} ...")
        result = download_http_file(url, target_file)
        print(f"    Done ({result['bytes']:,} bytes, sha256={result['sha256'][:16]}...)")


if __name__ == "__main__":
    main()
